using System.Globalization;
using System.Text.RegularExpressions;

namespace UuDok.Core.Rules;

public sealed record OcrLine(string Text, double X, double Y, double W, double H);

/// <summary>Lokal OCR av et bilde slik det vises. Agreement = to bildevarianter ga samme tekst.</summary>
public sealed record OcrInfo(string ObjectRef, List<OcrLine> Lines, bool Agreement, string? Language, int ImageWidth, int ImageHeight)
{
    public string Text => string.Join("\n", Lines.Select(l => l.Text));
}

public sealed class AnalysisResult
{
    public List<Finding> Findings { get; } = [];
    public Dictionary<string, RuleOutcome> Outcomes { get; } = [];
    public Dictionary<string, string> OutcomeNotes { get; } = [];
}

/// <summary>Kjører regelregisterets regler mot dokumentmodellen. Resultatene er «oppdaget», ikke reparert.</summary>
public sealed partial class RuleEngine(RuleRegistry registry)
{
    private int _n;
    private const string MainProfile = "no";

    public AnalysisResult Run(DocumentModel m, IReadOnlyDictionary<string, OcrInfo>? ocr = null, bool ocrAvailable = false)
    {
        var res = new AnalysisResult();
        var kind = m.Kind == DocumentKind.Docx ? "docx" : "pptx";
        foreach (var rule in registry.Rules)
        {
            if (!rule.AppliesTo.Contains(kind)) { res.Outcomes[rule.Id] = RuleOutcome.NotApplicable; continue; }
            var before = res.Findings.Count;
            var (applicable, tested) = Evaluate(rule, m, res, ocr, ocrAvailable);
            var found = res.Findings.Count - before;
            res.Outcomes[rule.Id] =
                !tested ? RuleOutcome.NotTested :
                !applicable ? RuleOutcome.NotApplicable :
                found > 0 ? (res.Findings.Skip(before).Any(f => f.Outcome == RuleOutcome.Failed) ? RuleOutcome.Failed : RuleOutcome.NeedsReview) :
                rule.CanPass ? RuleOutcome.Passed : RuleOutcome.NeedsReview;
        }
        return res;
    }

    private Finding F(RuleDef r, DocumentModel m, DocObject? o, string desc, Severity sev, RuleOutcome outcome, VisualRisk risk,
        bool auto, bool visible, string? action = null, string? uncertainty = null, string? group = null, params Evidence[] ev)
    {
        var obj = o?.Ref ?? new ObjectRef(m.Kind == DocumentKind.Docx ? "/word/document.xml" : "/ppt/presentation.xml", "part");
        return new Finding
        {
            Id = $"F{++_n:D4}", RuleId = r.Id, Profile = MainProfile, Object = obj, Location = Location(m, o),
            Description = desc, Severity = sev, Criteria = r.Refs.SelectMany(kv => kv.Value.Select(v => $"{kv.Key}: {v}")).ToList(),
            SuggestedAction = action, Uncertainty = uncertainty, VisualRisk = risk, AutoRepairSupported = auto,
            RequiresVisibleChange = visible, Outcome = outcome, Group = group ?? r.Id, Evidence = ev.ToList(),
        };
    }

    public static string Location(DocumentModel m, DocObject? o)
    {
        if (o == null) return "Hele dokumentet";
        var name = o.Name != null ? $"«{o.Name}»" : o.Type.ToString();
        if (o.SlideNumber is { } s) return $"Lysbilde {s}, {name}";
        var part = o.Extra.GetValueOrDefault("part", "Hoveddokument");
        return o.Type switch
        {
            ObjectType.Paragraph or ObjectType.Heading or ObjectType.ListItem => $"{part}, avsnitt «{Short(o.Text)}»",
            ObjectType.Hyperlink => $"{part}, lenke «{Short(o.Text)}»",
            ObjectType.Table => $"{part}, tabell «{Short(o.Text)}»",
            _ => $"{part}, {name}" + (o.ContextBefore != null ? $" (etter «{Short(o.ContextBefore, 40)}»)" : "")
        };
    }

    private static string Short(string? s, int n = 60) => s == null ? "" : (s.Replace('\n', ' ').Trim() is var t && t.Length > n ? t[..n] + "…" : t);

    private static bool NeedsAlt(DocObject o) =>
        !o.Decorative && o.Extra.GetValueOrDefault("hidden") != "1" &&
        (o.Type is ObjectType.Picture or ObjectType.Chart or ObjectType.SmartArt or ObjectType.OleObject
         || (o.Type == ObjectType.Shape && o.Extra.ContainsKey("imageFill"))
         || (o.Type == ObjectType.Group && o.Depth == 0));

    private static bool InsideDescribedGroup(DocumentModel m, DocObject o) =>
        o.ParentLocator != null && m.Objects.Any(p => p.Ref.PartUri == o.Ref.PartUri && p.Ref.Locator == o.ParentLocator && (p.Decorative || !string.IsNullOrWhiteSpace(p.AltText)));

    [GeneratedRegex(@"(\.(png|jpe?g|gif|bmp|svg|emf|wmf|tiff?)$)|^(img|dsc|image|screenshot|skjermbilde|bilde|picture)[\s_-]?\d+", RegexOptions.IgnoreCase)]
    private static partial Regex FileNameLike();
    [GeneratedRegex(@"(et bilde som inneholder|bilde som inneholder|a picture containing|beskrivelse er generert automatisk|description automatically generated|automatisk generert beskrivelse)", RegexOptions.IgnoreCase)]
    private static partial Regex AutoGenerated();
    [GeneratedRegex(@"^\s*\p{Ll}[\p{L}-]*(\s*,\s*\p{Ll}[\p{L}-]*){2,}\s*$")]
    private static partial Regex ObjectList();

    private static readonly HashSet<string> GenericWords = new(StringComparer.OrdinalIgnoreCase)
        { "bilde", "image", "picture", "foto", "photo", "graf", "graph", "diagram", "figur", "figure", "grafikk", "illustrasjon", "illustration", "chart", "tekst", "text", "skjermbilde", "screenshot", "ikon", "icon", "logo" };

    public static string? AltProblem(string alt, DocObject o)
    {
        var a = alt.Trim();
        if (AutoGenerated().IsMatch(a)) return "ser ut som en automatisk generert beskrivelse";
        if (FileNameLike().IsMatch(a)) return "ser ut som et filnavn";
        if (GenericWords.Contains(a.TrimEnd('.'))) return "er bare et generelt ord";
        if (ObjectList().IsMatch(a)) return "er en liste med objekter uten sammenheng";
        if (o.Caption != null && string.Equals(a, o.Caption, StringComparison.OrdinalIgnoreCase)) return "gjentar bildeteksten ordrett";
        return null;
    }

    [GeneratedRegex(@"^(her|klikk her|trykk her|klikk|les mer|mer|mer info|mer informasjon|lenke|link|denne lenken|this link|here|click here|read more|more|>>|»|→)\.?$", RegexOptions.IgnoreCase)]
    private static partial Regex VagueLink();
    [GeneratedRegex(@"^(https?://|www\.)", RegexOptions.IgnoreCase)]
    private static partial Regex RawUrl();

    private (bool applicable, bool tested) Evaluate(RuleDef r, DocumentModel m, AnalysisResult res, IReadOnlyDictionary<string, OcrInfo>? ocr, bool ocrAvailable)
    {
        switch (r.Id)
        {
            case "ALT-MISSING":
            {
                var items = m.Objects.Where(NeedsAlt).ToList();
                foreach (var o in items.Where(o => string.IsNullOrWhiteSpace(o.AltText) && !InsideDescribedGroup(m, o)))
                {
                    var group = o.Type switch { ObjectType.Chart => "Diagrammer uten beskrivelse", ObjectType.SmartArt => "SmartArt uten beskrivelse", ObjectType.Group => "Grupper uten beskrivelse", _ => "Bilder uten beskrivelse" };
                    res.Findings.Add(F(r, m, o, $"{TypeName(o)} mangler alternativ tekst.", Severity.High, RuleOutcome.Failed, VisualRisk.None,
                        auto: true, visible: false, action: "Skriv en kort beskrivelse av hva bildet viser og hvorfor det er der, eller marker det som dekorativt.", group: group));
                }
                return (items.Count > 0, true);
            }
            case "ALT-POOR":
            {
                var items = m.Objects.Where(o => NeedsAlt(o) && !string.IsNullOrWhiteSpace(o.AltText)).ToList();
                foreach (var o in items)
                    if (AltProblem(o.AltText!, o) is { } why)
                        res.Findings.Add(F(r, m, o, $"Den alternative teksten «{Short(o.AltText, 80)}» {why}.", Severity.Medium, RuleOutcome.NeedsReview, VisualRisk.None,
                            auto: true, visible: false, action: "Erstatt med en beskrivelse av innhold og funksjon i sammenhengen.", group: "Svake beskrivelser",
                            ev: new Evidence("eksisterende", o.AltText!)));
                return (items.Count > 0, true);
            }
            case "ALT-TEXTIMAGE":
            {
                if (!ocrAvailable || ocr == null) return (true, false);
                bool any = false;
                foreach (var o in m.Objects.Where(o => o.Type == ObjectType.Picture && !o.Decorative))
                {
                    if (!ocr.TryGetValue(o.Ref.ToString(), out var info) || info.Lines.Count == 0) continue;
                    any = true;
                    var covered = (o.AltText ?? "") + " " + o.Caption + " " + o.ContextBefore + " " + o.ContextAfter + " " +
                                  (o.SlideNumber is { } sn ? m.Slides.FirstOrDefault(s => s.Number == sn)?.AllVisibleText : "");
                    var missing = info.Lines.Where(l => l.Text.Length >= 3 && !Contains(covered, l.Text)).ToList();
                    if (missing.Count == 0) continue;
                    res.Findings.Add(F(r, m, o, $"Bildet inneholder tekst som ikke er tilgjengelig som tekst: «{Short(string.Join(" / ", missing.Select(l => l.Text)), 120)}».",
                        Severity.High, RuleOutcome.Failed, VisualRisk.None, auto: true, visible: false,
                        action: "Teksten tas med i bildets alternative tekst (og som lysbildetittel når den er en tittel). Vurder også synlig tekst (1.4.5).",
                        uncertainty: info.Agreement ? null : "OCR ga ulike resultater for bildevarianter; teksten kan være feillest.",
                        group: "Tekst i bilder", ev: new Evidence("ocr", info.Text)));
                }
                return (any || m.Objects.Any(o => o.Type == ObjectType.Picture), true);
            }
            case "ALT-COMPLEX":
            {
                var items = m.Objects.Where(o => o.Type is ObjectType.Chart or ObjectType.SmartArt && !o.Decorative).ToList();
                foreach (var o in items)
                    res.Findings.Add(F(r, m, o, $"{TypeName(o)} kan inneholde mer informasjon enn en kort tekst kan formidle.", Severity.Low, RuleOutcome.NeedsReview, VisualRisk.None,
                        auto: false, visible: false, action: "Vurder om informasjonen også finnes som tekst eller tabell i dokumentet. Appen lager et utkast til lang beskrivelse.",
                        group: "Komplekse figurer", ev: o.Extra.TryGetValue("chartData", out var cd) ? [new Evidence("diagramdata", cd)] : o.Extra.TryGetValue("smartArtText", out var st) ? [new Evidence("smartart", st)] : []));
                return (items.Count > 0, true);
            }
            case "DECOR-CANDIDATE":
            {
                var items = m.Objects.Where(o => !o.Decorative && string.IsNullOrWhiteSpace(o.AltText) && o.Depth == 0 && IsDecorCandidate(o)).ToList();
                foreach (var o in items)
                {
                    var sure = o.Extra.ContainsKey("connector") || Thin(o);
                    res.Findings.Add(F(r, m, o, sure ? $"{TypeName(o)} ser ut som en ren dekorasjon (linje)." : $"{TypeName(o)} uten tekst kan være dekorasjon.",
                        Severity.Low, sure ? RuleOutcome.Failed : RuleOutcome.NeedsReview, VisualRisk.None, auto: sure, visible: false,
                        action: "Marker som dekorativ, slik at skjermlesere hopper over den.", group: "Mulige dekorasjoner",
                        uncertainty: sure ? null : "Formen kan bære mening (for eksempel en pil eller fargekode)."));
                }
                return (m.Objects.Any(o => o.Type is ObjectType.Shape or ObjectType.Picture), true);
            }
            case "DOC-TITLE":
                if (m.Title == null)
                    res.Findings.Add(F(r, m, null, "Dokumentet har ingen tittel i dokumentegenskapene. Skjermlesere og nettlesere viser da filnavnet.", Severity.Medium,
                        RuleOutcome.Failed, VisualRisk.None, auto: true, visible: false, action: "Sett tittel i dokumentegenskapene."));
                return (true, true);
            case "SLIDE-TITLE":
            {
                foreach (var s in m.Slides.Where(s => s.TitleText == null))
                    res.Findings.Add(F(r, m, new DocObject { Ref = new ObjectRef(s.PartUri, "part"), Type = ObjectType.Slide, SlideNumber = s.Number, Name = "lysbilde" },
                        $"Lysbilde {s.Number} har ingen tittel. Skjermleserbrukere navigerer etter lysbildetitler.", Severity.Medium, RuleOutcome.Failed, VisualRisk.None,
                        auto: true, visible: false, action: "Legg til en skjult tittel som beskriver lysbildet (utenfor lysbildet, ingen synlig endring).", group: "Lysbilder uten tittel"));
                return (m.Slides.Count > 0, true);
            }
            case "SLIDE-TITLE-UNIQUE":
            {
                foreach (var g in m.Slides.Where(s => s.TitleText != null).GroupBy(s => s.TitleText!.Trim().ToLowerInvariant()).Where(g => g.Count() > 1))
                    res.Findings.Add(F(r, m, null, $"{g.Count()} lysbilder har tittelen «{Short(g.First().TitleText)}» (lysbilde {string.Join(", ", g.Select(s => s.Number))}).",
                        Severity.Info, RuleOutcome.NeedsReview, VisualRisk.None, auto: false, visible: false,
                        action: "Vurder om titlene bør skilles, for eksempel «Oppgave 1» og «Oppgave 2». Appen lager ikke kunstige titler.", group: "Like lysbildetitler"));
                return (m.Slides.Count > 1, true);
            }
            case "LANG-DOC":
            {
                var text = m.Kind == DocumentKind.Docx
                    ? string.Join(" ", m.Objects.Where(o => o.Type is ObjectType.Paragraph or ObjectType.Heading or ObjectType.ListItem).Select(o => o.Text))
                    : string.Join(" ", m.Slides.Select(s => s.AllVisibleText));
                var guess = LanguageGuess.Detect(text);
                if (m.Kind == DocumentKind.Docx && m.DefaultLanguage == null)
                    res.Findings.Add(F(r, m, null, "Dokumentet har ikke satt standardspråk.", Severity.Medium, RuleOutcome.Failed, VisualRisk.Low,
                        auto: guess.Language != null && guess.Confidence >= 0.3, visible: false,
                        action: guess.Language != null ? $"Sett standardspråk til {guess.Language} (gjenkjent fra teksten)." : "Sett standardspråk.",
                        uncertainty: guess.Confidence < 0.3 ? "Språket i teksten kunne ikke bestemmes sikkert." : null,
                        ev: new Evidence("språkgjenkjenning", $"{guess.Language ?? "ukjent"} (margin {guess.Confidence.ToString(CultureInfo.InvariantCulture)}, {guess.WordCount} ord)")));
                else if (m.Kind == DocumentKind.Docx && guess.Language != null && guess.Confidence >= 0.5 && !LanguageGuess.SameFamily(guess.Language, m.DefaultLanguage))
                    res.Findings.Add(F(r, m, null, $"Standardspråket er {m.DefaultLanguage}, men teksten ser ut til å være {guess.Language}.", Severity.Medium, RuleOutcome.NeedsReview, VisualRisk.Low,
                        auto: false, visible: false, action: "Kontroller dokumentspråket i Word (Se gjennom → Språk)."));
                else if (m.Kind == DocumentKind.Pptx)
                {
                    var total = m.RunLanguages.Values.Sum();
                    if (total == 0) return (false, true);
                    var dominant = m.RunLanguages.OrderByDescending(kv => kv.Value).First();
                    if (dominant.Key == "(ikke satt)")
                        res.Findings.Add(F(r, m, null, "Teksten i presentasjonen har ikke språkmerking.", Severity.Medium, RuleOutcome.Failed, VisualRisk.Low,
                            auto: false, visible: false, action: "Velg all tekst og angi språk i PowerPoint (Se gjennom → Språk)."));
                    else if (guess.Language != null && guess.Confidence >= 0.5 && guess.WordCount >= 40 && !LanguageGuess.SameFamily(guess.Language, dominant.Key))
                        res.Findings.Add(F(r, m, null, $"Det meste av teksten er merket som {dominant.Key}, men ser ut til å være {guess.Language}. Skjermlesere kan da lese med feil uttale.",
                            Severity.Medium, RuleOutcome.Failed, VisualRisk.Low, auto: false, visible: false,
                            action: "Velg all tekst og angi riktig språk i PowerPoint (Se gjennom → Språk → Angi korrekturspråk).",
                            ev: new Evidence("språkmerking", string.Join(", ", m.RunLanguages.OrderByDescending(kv => kv.Value).Select(kv => $"{kv.Key}: {kv.Value} tegn")))));
                }
                return (true, true);
            }
            case "LANG-PARTS": return (true, false);
            case "HEAD-NONE":
            {
                var paras = m.Objects.Where(o => o.Type is ObjectType.Paragraph or ObjectType.Heading or ObjectType.ListItem && !string.IsNullOrWhiteSpace(o.Text)).ToList();
                if (paras.Count > 20 && !paras.Any(p => p.Type == ObjectType.Heading))
                    res.Findings.Add(F(r, m, null, $"Dokumentet har {paras.Count} avsnitt, men ingen overskrifter.", Severity.High, RuleOutcome.Failed, VisualRisk.None,
                        auto: false, visible: false, action: "Bruk overskriftsstiler for å dele inn dokumentet."));
                return (paras.Count > 20, true);
            }
            case "HEAD-FAKE":
            {
                foreach (var o in m.Objects.Where(o => o.Extra.ContainsKey("looksLikeHeading")))
                    res.Findings.Add(F(r, m, o, $"«{Short(o.Text)}» ser ut som en overskrift (stor eller fet tekst), men er ikke merket som overskrift.",
                        Severity.Medium, RuleOutcome.NeedsReview, VisualRisk.None, auto: true, visible: false,
                        action: $"Merk som overskrift nivå {o.Extra["looksLikeHeading"]} uten å endre utseendet (dispositionsnivå).",
                        uncertainty: "Vurdert ut fra skriftstørrelse og fet skrift; det kan være utheving og ikke overskrift.", group: "Mulige overskrifter"));
                return (m.Objects.Any(o => o.Type is ObjectType.Paragraph), true);
            }
            case "HEAD-SKIP":
            {
                int prev = 0;
                foreach (var o in m.Objects.Where(o => o.Type == ObjectType.Heading && o.Extra.GetValueOrDefault("part") == "Hoveddokument"))
                {
                    if (o.HeadingLevel > prev + 1 && prev > 0)
                        res.Findings.Add(F(r, m, o, $"Overskriften «{Short(o.Text)}» er nivå {o.HeadingLevel} etter nivå {prev}.", Severity.Low, RuleOutcome.Failed,
                            VisualRisk.Medium, auto: false, visible: true, action: "Juster nivået i Word, eventuelt i «Tillat synlige forbedringer»."));
                    prev = o.HeadingLevel ?? prev;
                }
                return (m.Objects.Any(o => o.Type == ObjectType.Heading), true);
            }
            case "LIST-FAKE":
            {
                foreach (var o in m.Objects.Where(o => o.Extra.ContainsKey("fakeList")))
                    res.Findings.Add(F(r, m, o, $"«{Short(o.Text)}» ser ut som et listepunkt laget med tegn.", Severity.Low, RuleOutcome.NeedsReview, VisualRisk.Medium,
                        auto: false, visible: true, action: "Bruk Words punktliste eller nummerert liste.", group: "Falske lister"));
                return (m.Objects.Any(o => o.Type is ObjectType.Paragraph or ObjectType.ListItem), true);
            }
            case "TABLE-HEADER":
            {
                var tables = m.Objects.Where(o => o.Type == ObjectType.Table).ToList();
                foreach (var t in tables.Where(t => t.Extra.GetValueOrDefault("headerRow") != "1" && int.Parse(t.Extra.GetValueOrDefault("rows", "0")) > 1))
                    res.Findings.Add(F(r, m, t, "Tabellen har ingen markert overskriftsrad.", Severity.Medium, RuleOutcome.Failed,
                        m.Kind == DocumentKind.Docx ? VisualRisk.Low : VisualRisk.Medium, auto: m.Kind == DocumentKind.Docx, visible: m.Kind == DocumentKind.Pptx,
                        action: m.Kind == DocumentKind.Docx ? "Marker første rad som overskriftsrad (kontrolleres visuelt fordi raden gjentas på nye sider)." : "Slå på «Overskriftsrad» for tabellen (kan endre tabellens utseende).",
                        uncertainty: "Første rad antas å være overskrifter.", group: "Tabeller uten overskriftsrad"));
                return (tables.Count > 0, true);
            }
            case "TABLE-MERGED":
            {
                var tables = m.Objects.Where(o => o.Type == ObjectType.Table).ToList();
                foreach (var t in tables.Where(t => t.Extra.GetValueOrDefault("merged") == "1"))
                    res.Findings.Add(F(r, m, t, "Tabellen har sammenslåtte celler, som kan være vanskelige å navigere med skjermleser.", Severity.Low, RuleOutcome.NeedsReview,
                        VisualRisk.High, auto: false, visible: true, action: "Vurder en enklere tabellstruktur. Appen endrer ikke tabellen.", group: "Sammenslåtte celler"));
                return (tables.Count > 0, true);
            }
            case "LINK-PURPOSE":
            {
                var links = m.Objects.Where(o => o.Type == ObjectType.Hyperlink).ToList();
                foreach (var l in links.Where(l => l.Text != null && VagueLink().IsMatch(l.Text.Trim())))
                    res.Findings.Add(F(r, m, l, $"Lenketeksten «{l.Text!.Trim()}» sier ikke hvor lenken går{(l.HyperlinkTarget != null ? $" ({l.HyperlinkTarget})" : "")}.",
                        Severity.Medium, RuleOutcome.Failed, VisualRisk.Medium, auto: false, visible: true,
                        action: "Bytt til en tekst som beskriver målet (krever synlig endring).", group: "Uklare lenketekster",
                        ev: new Evidence("kontekst", Short(l.ContextBefore, 200))));
                return (links.Count > 0, true);
            }
            case "LINK-RAWURL":
            {
                var links = m.Objects.Where(o => o.Type == ObjectType.Hyperlink).ToList();
                foreach (var l in links.Where(l => l.Text != null && RawUrl().IsMatch(l.Text.Trim()) && l.Text.Trim().Length > 30))
                    res.Findings.Add(F(r, m, l, $"Lenken vises som en lang nettadresse: «{Short(l.Text, 80)}».", Severity.Low, RuleOutcome.Failed, VisualRisk.Medium,
                        auto: false, visible: true, action: "Bruk en beskrivende lenketekst.", group: "Nettadresser som lenketekst"));
                return (links.Count > 0, true);
            }
            case "CONTRAST-TEXT":
            {
                if (m.Kind == DocumentKind.Pptx) return (true, false);
                bool any = false;
                foreach (var o in m.Objects.Where(o => o.Extra.ContainsKey("contrast")))
                {
                    any = true;
                    var cr = double.Parse(o.Extra["contrast"], CultureInfo.InvariantCulture);
                    var large = o.Extra["large"] == "1";
                    var need = large ? 3.0 : 4.5;
                    if (cr >= need) continue;
                    res.Findings.Add(F(r, m, o, $"Tekstkontrasten er {cr.ToString("0.0", CultureInfo.GetCultureInfo("nb-NO"))}:1 ({o.Extra["fg"]} på {o.Extra["bg"]}); minst {need.ToString("0.0", CultureInfo.GetCultureInfo("nb-NO"))}:1 kreves.",
                        Severity.High, RuleOutcome.Failed, VisualRisk.High, auto: false, visible: true,
                        action: "Bruk mørkere tekst eller lysere bakgrunn. Dette krever en synlig endring og løses ikke av en skjult beskrivelse.",
                        group: "Kontrastproblemer", ev: new Evidence("farger", $"{o.Extra["fg"]} / {o.Extra["bg"]}")));
                }
                return (any || m.Objects.Any(o => o.Type is ObjectType.Paragraph), true);
            }
            case "ORDER-SLIDE":
            {
                foreach (var s in m.Slides)
                {
                    var top = m.Objects.Where(o => o.SlideNumber == s.Number && o.Depth == 0 && o.Type != ObjectType.Hyperlink).OrderBy(o => o.TreeIndex).ToList();
                    var title = top.FirstOrDefault(o => o.PlaceholderType is "title" or "ctrTitle");
                    if (title == null) continue;
                    var before = top.TakeWhile(o => o != title).Where(o => !o.Decorative && (o.Text?.Length > 0 || NeedsAlt(o))).ToList();
                    if (before.Count == 0) continue;
                    var overlaps = before.Any(b => b.Bounds != null && title.Bounds != null && b.Bounds.Intersects(title.Bounds));
                    res.Findings.Add(F(r, m, title, $"Tittelen leses ikke først på lysbilde {s.Number}; {before.Count} objekt(er) leses før den.",
                        Severity.Medium, RuleOutcome.Failed, overlaps ? VisualRisk.High : VisualRisk.None, auto: !overlaps, visible: false,
                        action: overlaps ? "Tittelen overlapper et objekt som leses før; flytt rekkefølgen i PowerPoints leserekkefølge-rute." : "Flytt tittelen først i leserekkefølgen (ingen overlapping, ingen synlig endring).",
                        group: "Leserekkefølge"));
                }
                return (m.Slides.Count > 0, true);
            }
            case "ORDER-FLOAT":
            {
                var floats = m.Objects.Where(o => o.Extra.GetValueOrDefault("floating") == "1" && !o.Decorative).ToList();
                foreach (var o in floats)
                    res.Findings.Add(F(r, m, o, $"{TypeName(o)} er plassert flytende og kan bli lest på et uventet sted.", Severity.Low, RuleOutcome.NeedsReview, VisualRisk.High,
                        auto: false, visible: true, action: "Vurder «På linje med tekst» der det passer.", group: "Flytende objekter"));
                return (floats.Count > 0, true);
            }
            case "MEDIA-CAPTIONS":
            {
                var media = m.Objects.Where(o => o.Type == ObjectType.Media).ToList();
                foreach (var o in media)
                    res.Findings.Add(F(r, m, o, "Video eller lyd: appen kan ikke bekrefte teksting, transkripsjon eller synstolking.", Severity.Medium, RuleOutcome.NeedsReview,
                        VisualRisk.None, auto: false, visible: false, action: "Kontroller at mediet har teksting og eventuelt transkripsjon.", group: "Medier"));
                return (media.Count > 0, true);
            }
            case "INFO-SIGNED":
                if (m.IsSigned) res.Findings.Add(F(r, m, null, "Dokumentet er digitalt signert. Endringer gjør signaturen ugyldig.", Severity.Info, RuleOutcome.NeedsReview, VisualRisk.None, false, false));
                return (m.IsSigned, true);
            case "INFO-PROTECTED":
                if (m.HasProtection) res.Findings.Add(F(r, m, null, "Dokumentet er beskyttet mot redigering. Appen endrer det ikke.", Severity.Info, RuleOutcome.NeedsReview, VisualRisk.None, false, false));
                return (m.HasProtection, true);
            default:
                return (true, false);
        }
    }

    private static bool IsDecorCandidate(DocObject o) =>
        o.Extra.ContainsKey("connector") || (o.Type == ObjectType.Picture && Thin(o)) ||
        (o.Type == ObjectType.Shape && !o.IsPlaceholder && string.IsNullOrWhiteSpace(o.Text) && !o.Extra.ContainsKey("imageFill"));

    private static bool Thin(DocObject o) =>
        o.Bounds is { } b && b.Cx > 0 && b.Cy > 0 && (Math.Max(b.Cx, b.Cy) / (double)Math.Min(b.Cx, b.Cy) >= 15);

    private static bool Contains(string hay, string needle)
    {
        static string N(string s) => Regex.Replace(s.ToLowerInvariant(), @"[^\p{L}\p{N}]+", " ").Trim();
        return N(hay).Contains(N(needle));
    }

    public static string TypeName(DocObject o) => o.Type switch
    {
        ObjectType.Picture => "Bildet", ObjectType.Chart => "Diagrammet", ObjectType.SmartArt => "SmartArt-grafikken", ObjectType.Group => "Gruppen",
        ObjectType.OleObject => "Det innebygde objektet", ObjectType.Shape => "Figuren", ObjectType.TextBox => "Tekstboksen", ObjectType.Media => "Mediet",
        _ => "Objektet"
    } + (o.Name != null ? $" «{o.Name}»" : "");
